"""Turn a trained scikit-learn DecisionTreeClassifier into plain MicroPython code.

The generated module has one function, predict(x) -> (class_index, confidence),
made of nested if/else statements. It needs no library on the Pico.
Confidence is the share of training samples of the predicted class in the leaf.
"""

import datetime

MAX_DEPTH = 12  # deeper nesting makes the generated file large and hard to read


def tree_to_micropython(tree, classes, feature_names, note=""):
    t = tree.tree_
    if tree.get_depth() > MAX_DEPTH:
        raise ValueError("Tree depth %d is above %d; train with max_depth" % (tree.get_depth(), MAX_DEPTH))

    lines = [
        "# Generated by export_tree.py on %s. Do not edit by hand." % datetime.date.today().isoformat(),
        "# Depth %d, %d leaves. %s" % (tree.get_depth(), tree.get_n_leaves(), note),
        "",
        "CLASSES = %r" % (tuple(str(c) for c in classes),),
        "N_FEATURES = %d" % len(feature_names),
        "",
        "",
        "def predict(x):",
    ]

    def leaf(node):
        counts = t.value[node][0]
        total = float(sum(counts))
        best = int(counts.argmax())
        return best, round(float(counts[best]) / total, 3)

    def walk(node, depth):
        pad = "    " * depth
        left, right = t.children_left[node], t.children_right[node]
        if left == right:  # leaf
            cls, conf = leaf(node)
            lines.append("%sreturn %d, %r" % (pad, cls, conf))
            return
        f = t.feature[node]
        lines.append("%sif x[%d] <= %r:  # %s" % (pad, f, float(t.threshold[node]), feature_names[f]))
        walk(left, depth + 1)
        lines.append("%selse:" % pad)
        walk(right, depth + 1)

    walk(0, 1)
    return "\n".join(lines) + "\n"
